import assert from "node:assert/strict";
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";
import { beginHookHealth, bindHealthContext, markHealthDenied, markHealthFailure, createHealthJournal, healthSessionKey, HEALTH_BUCKET_MS } from "../lib/runtime-health.mjs";

assert.ok(process.env.AGENT_COORD_HOME, "run through the isolated runner");
const home = process.env.AGENT_COORD_HOME;
let at = 100 * HEALTH_BUCKET_MS;
const sink = createHealthJournal({ home: join(home, "privacy"), enabled: true, now: () => at });
const input = { session_id: "private-session-id", hook_event_name: "PreToolUse", prompt: "PRIVATE_PROMPT", cwd: "PRIVATE_PATH", tool_input: { command: "PRIVATE_COMMAND", body: "PRIVATE_MESSAGE" } };
const hook = beginHookHealth("codex", input, { sink, elapsed: () => 12.3456 });
bindHealthContext({ agentId: "fixture-agent", ws: "aaaaaaaaaaaaaaaa" });
markHealthDenied();
hook.finish(2); hook.finish(2);
const text = readFileSync(join(sink.dir, `h-100.jsonl`), "utf8");
for (const secret of ["PRIVATE_", "private-session-id"]) assert.ok(!text.includes(secret), secret);
const events = text.trim().split("\n").map(JSON.parse);
assert.equal(events.length, 2);
assert.equal(events[1].outcome, "denied");
assert.equal(events[1].ms, 12.346);
assert.equal(events[1].agent, "fixture-agent");
assert.equal(events[1].error, undefined);
assert.notEqual(healthSessionKey(input), healthSessionKey({ ...input, agent_id: "child" }));
const failed = beginHookHealth("codex", input, { sink, elapsed: () => 50 });
markHealthFailure({ code: "COORD_DEADLINE", message: "PRIVATE_ERROR" });
markHealthDenied(); failed.finish();
const last = JSON.parse(readFileSync(join(sink.dir, "h-100.jsonl"), "utf8").trim().split("\n").at(-1));
assert.equal(last.error, "deadline"); assert.equal(last.outcome, "error"); assert.equal(last.denied, true);
assert.ok(!JSON.stringify(last).includes("PRIVATE_ERROR"));
const extendedIo = beginHookHealth("codex", input, { sink, elapsed: () => 70 });
markHealthFailure({ code: "ERR_SQLITE_ERROR", errcode: 1290, message: "PRIVATE_IO_PATH" }); extendedIo.finish();
assert.equal(JSON.parse(readFileSync(join(sink.dir, "h-100.jsonl"), "utf8").trim().split("\n").at(-1)).error, "io");
sink.write({ phase: "mcp", agent: "fixture-agent", provider: "codex", version: "1.0.0", ...input });
assert.ok(!readFileSync(join(sink.dir, "h-100.jsonl"), "utf8").includes("PRIVATE_"), "persistence boundary drops unexpected payload fields");
assert.doesNotThrow(() => beginHookHealth("codex", input, { sink: { write() { throw new Error("offline"); } } }).finish());
let writes = 0;
const flaky = beginHookHealth("codex", input, { sink: { write() { if (writes++) throw new Error("offline"); return true; } } });
assert.doesNotThrow(() => flaky.finish());
const disabled = createHealthJournal({ home: join(home, "off"), enabled: false });
beginHookHealth("codex", input, { sink: disabled }).finish();
assert.ok(!existsSync(disabled.dir));
const tiny = createHealthJournal({ home: join(home, "tiny"), enabled: true, now: () => at, maxBytes: 150 });
assert.equal(tiny.write({ phase: "mcp", agent: "fixture", provider: "codex", version: "1.0.0" }), true);
assert.equal(tiny.write({ phase: "mcp", agent: "fixture", provider: "codex", version: "1.0.0" }), false);
assert.ok(existsSync(join(tiny.dir, "h-100.jsonl.overflow")));
at += 7 * HEALTH_BUCKET_MS;
sink.write({ phase: "mcp", agent: "fixture", provider: "codex", version: "1.0.0" });
assert.ok(!existsSync(join(sink.dir, "h-100.jsonl")), "old owned buckets expire");

const worker = fileURLToPath(new URL("_runtime-health-worker.mjs", import.meta.url));
const run = (store, hang = false) => new Promise((resolve, reject) => {
  const child = spawn(process.execPath, [worker, ...(hang ? ["--hang"] : [])], { windowsHide: true,
    env: { ...process.env, AGENT_COORD_HOME: store, AGENT_COORD_HEALTH: "1" }, stdio: ["ignore", "pipe", "pipe"] });
  const timeout = setTimeout(() => { child.kill(); reject(new Error("fixture child timeout")); }, 5000);
  child.on("error", reject);
  if (hang) child.stdout.once("data", () => child.kill("SIGKILL"));
  child.on("close", code => { clearTimeout(timeout); if (hang || code === 0) resolve(); else reject(new Error(`worker exit ${code}`)); });
});
const concurrent = join(home, "concurrent");
await Promise.all(Array.from({ length: 8 }, () => run(concurrent)));
const journalRows = dir => readdirSync(join(dir, "health")).filter(f => f.endsWith(".jsonl"))
  .flatMap(f => readFileSync(join(dir, "health", f), "utf8").trim().split("\n").map(JSON.parse));
const rows = journalRows(concurrent);
assert.equal(rows.length, 16); assert.equal(new Set(rows.map(r => r.id)).size, 8);
const killed = join(home, "killed");
await run(killed, true);
assert.deepEqual(journalRows(killed).map(r => r.phase), ["start"], "killed writer cannot manufacture a completion");
console.log("Runtime health: private fields only, separate failures/denials, safe I/O failure, opt-out, bounded retention, atomic concurrent records and visible killed writer");
