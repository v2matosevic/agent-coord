import { writeFileSync, chmodSync, copyFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { homedir } from "node:os";
import { COORD_HOME } from "../lib/identity.mjs";

// Generate + install the SwiftBar/xbar menu-bar plugin for agent-coord (macOS).
// The plugin is a tiny bash stub that resolves node (GUI apps don't inherit your
// fnm/Homebrew PATH) and execs the read-only renderer cli/macos-menubar.mjs. The
// stub bakes an absolute repo path, so it's written to the machine-local store
// dir (~/.agent-coord), NOT the repo — nothing machine-specific gets committed.

if (process.platform !== "darwin") {
  console.log("macOS menu-bar plugin: skipped (not macOS).");
  process.exit(0);
}

const ROOT = dirname(dirname(fileURLToPath(import.meta.url))).replace(/\\/g, "/");
const REFRESH = "5s"; // SwiftBar refresh interval, encoded in the filename
const PLUGIN_NAME = `agent-coord.${REFRESH}.sh`;

const stub = `#!/bin/bash
# <xbar.title>agent-coord Fleet</xbar.title>
# <xbar.version>v1.0</xbar.version>
# <xbar.author>Version2</xbar.author>
# <xbar.desc>Live AI coding-agent coordination fleet in the menu bar.</xbar.desc>
# <swiftbar.runInBash>true</swiftbar.runInBash>
# Auto-generated by cli/install-macos-menubar.mjs — do not edit by hand.
# GUI apps get a minimal PATH, so resolve node (fnm default alias / Homebrew) first.
export PATH="$HOME/.local/share/fnm/aliases/default/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
NODE="$(command -v node || true)"
if [ -z "$NODE" ]; then
  echo "coord ? | color=#8a8a8a"; echo "---"
  echo "node not found on PATH (install Node, or run 'fnm default <version>')"
  exit 0
fi
exec "$NODE" --disable-warning=ExperimentalWarning "${ROOT}/cli/macos-menubar.mjs"
`;

mkdirSync(COORD_HOME, { recursive: true });
const canonical = join(COORD_HOME, PLUGIN_NAME);
writeFileSync(canonical, stub);
try {
  chmodSync(canonical, 0o755);
} catch {}

// Locate a plugin folder: SwiftBar stores it in defaults; xbar uses a fixed path.
function swiftbarDir() {
  try {
    const d = execFileSync("defaults", ["read", "com.ambarlabs.SwiftBar", "PluginDirectory"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
    return d && existsSync(d) ? d : null;
  } catch {
    return null;
  }
}
const xbarDir = join(homedir(), "Library", "Application Support", "xbar", "plugins");
const target = swiftbarDir() || (existsSync(xbarDir) ? xbarDir : null);

let installedTo = null;
if (target) {
  try {
    const dest = join(target, PLUGIN_NAME);
    copyFileSync(canonical, dest);
    chmodSync(dest, 0o755);
    installedTo = dest;
  } catch {}
}

console.log("✅ macOS menu-bar plugin generated:", canonical);
if (installedTo) {
  console.log("✅ installed into your plugin folder:", installedTo);
  console.log("   SwiftBar/xbar will show it within a few seconds (or hit Refresh).");
} else {
  console.log("ℹ️  No SwiftBar/xbar plugin folder detected. To enable the menu bar:");
  console.log("     1) brew install --cask swiftbar        # (or xbar)");
  console.log("     2) launch SwiftBar, pick a plugin folder, then:");
  console.log(`        cp "${canonical}" "<plugin-folder>/"`);
  console.log("   (re-running this installer auto-copies once the folder exists)");
}
